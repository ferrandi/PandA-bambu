// Self checking testbench for lp_array_write.cpp, holding the output FIFO not
// ready. The bambu co-simulation cannot stimulate the stalling case of issue
// #434: it drives the ready signals high, and the RAM behind an `array`
// interface is external, so it has to be modelled here.
//
// The oracle is the delivered sequence: MEM[0..15] with no duplicates, losses or
// reordering under any backpressure pattern. A scenario is meaningful only if it
// also stalls a pending write, otherwise the verdict is INCONCLUSIVE.
//
// BP_MODE: 0 no backpressure, 1 alternating, 2 not ready for 28 cycles. -DMUT
// corrupts one memory word to check the sensitivity of the test.

`timescale 1 ns / 1 ps

module tb_lp_array_write;

   parameter DEPTH     = 16;
   parameter BP_MODE   = 0;
   parameter MAX_CYCLE = 4000;

   reg         clock = 1'b0;
   reg         reset = 1'b0;      // active low with the default options
   reg         start_port = 1'b0;
   reg  [31:0] arr_q0 = 32'b0;
   reg  [31:0] arr_q1 = 32'b0;
   reg         out_full_n = 1'b1;
   wire        done_port;
   wire        idle_port;
   wire [3:0]  arr_address0;
   wire [3:0]  arr_address1;
   wire        arr_ce0;
   wire        arr_ce1;
   wire [31:0] out_din;
   wire        out_write;

   // external RAM: registered output, like the BRAM behind mode="array"
   reg [31:0] mem [0:DEPTH-1];
   integer k;
   initial
      for (k = 0; k < DEPTH; k = k + 1)
         mem[k] = 32'd700000 + k;

   always @(posedge clock)
      if (arr_ce0) arr_q0 <= mem[arr_address0];
   always @(posedge clock)
      if (arr_ce1) arr_q1 <= mem[arr_address1];

   p_Z11store_stageRA16_iR10ac_channelIiE dut (
      .clock(clock),
      .reset(reset),
      .start_port(start_port),
      .arr_q0(arr_q0),
      .arr_q1(arr_q1),
      .out_full_n(out_full_n),
      .done_port(done_port),
      .idle_port(idle_port),
      .arr_address0(arr_address0),
      .arr_address1(arr_address1),
      .arr_ce0(arr_ce0),
      .arr_ce1(arr_ce1),
      .out_din(out_din),
      .out_write(out_write));

`ifdef MUT
   // A corrupted memory word must show up as a MISMATCH. Only the model is
   // touched, so no name generated by bambu is involved.
   initial
      #1 mem[3] = mem[3] + 32'd5;
`endif

   always #5 clock = ~clock;

   integer cycle = 0;
   always @(posedge clock)
   begin
      cycle = cycle + 1;
      if (!reset) out_full_n <= 1'b1;
      else if (BP_MODE == 0) out_full_n <= 1'b1;
      else if (BP_MODE == 1) out_full_n <= ((cycle % 5) < 2);
      else out_full_n <= !((cycle >= 14) && (cycle < 42));
   end

   integer n_checked = 0;
   integer errors = 0;
   integer first_bad_cycle = -1;
   integer pending_cycles = 0;
   integer started = 0;
   reg [31:0] exp;

   always @(posedge clock)
   begin
      if (reset && started && !done_port && !out_full_n && !out_write && n_checked < DEPTH)
         pending_cycles = pending_cycles + 1;

      if (reset && started && out_write && out_full_n)
      begin
         exp = 32'd700000 + n_checked;
         if (out_din !== exp)
         begin
            errors = errors + 1;
            if (first_bad_cycle < 0) first_bad_cycle = cycle;
            $display("  MISMATCH pos=%0d cycle=%0d: received %0d expected %0d",
                     n_checked, cycle, out_din, exp);
         end
         n_checked = n_checked + 1;
      end
`ifdef DEBUG
      if (cycle < 70)
         $display("cycle %0d idle=%b done=%b ce=%b addr=%0d q=%0d write=%b din=%0d full_n=%b",
                  cycle, idle_port, done_port, arr_ce0, arr_address0, arr_q0, out_write, out_din,
                  out_full_n);
`endif
   end

   integer wait_t = 0;
   integer start_cycle = 0;
   integer done_cycle = 0;

   initial
   begin
      $display("== tb_lp_array_write: BP_MODE=%0d ==", BP_MODE);

      repeat (4) @(posedge clock);
      reset <= 1'b1;
      repeat (3) @(posedge clock);

      // start must be given while idle_port is asserted
      wait_t = 0;
      while (!idle_port && wait_t < 50)
      begin
         @(posedge clock);
         wait_t = wait_t + 1;
      end
      start_port <= 1'b1;
      @(posedge clock);
      start_port <= 1'b0;
      started = 1;
      start_cycle = cycle;

      while (!done_port && (cycle - start_cycle) < MAX_CYCLE) @(posedge clock);
      done_cycle = cycle;
      // a controller that never completes must not pass, even with every word
      // delivered correctly
      if (!done_port)
      begin
         errors = errors + 1;
         $display("  ERROR: TIMEOUT, done_port never asserted");
      end

      // the distance, not the difference: more writes than DEPTH are an error too
      if (n_checked != DEPTH)
      begin
         errors = errors + ((n_checked > DEPTH) ? (n_checked - DEPTH) : (DEPTH - n_checked));
         $display("  ERROR: %0d writes delivered, %0d expected", n_checked, DEPTH);
      end
      $display("  writes checked = %0d, cycles = %0d, stalling = %0d",
               n_checked, done_cycle - start_cycle, pending_cycles);

      if (errors > 0)
      begin
         if (first_bad_cycle >= 0)
            $display("FAIL [BP=%0d] %0d errors, first bad data at cycle %0d", BP_MODE, errors, first_bad_cycle);
         else
            $display("FAIL [BP=%0d] %0d errors, no data mismatch", BP_MODE, errors);
      end
      else if ((BP_MODE != 0) && (pending_cycles == 0))
         $display("INCONCLUSIVE [BP=%0d] no stalling cycle with a pending write", BP_MODE);
      else
         $display("PASS [BP=%0d] %0d correct writes in %0d cycles (%0d stalling)",
                  BP_MODE, n_checked, done_cycle - start_cycle, pending_cycles);
      $finish;
   end

   initial
   begin
      #(MAX_CYCLE * 20);
      $display("FAIL [BP=%0d] global watchdog", BP_MODE);
      $finish;
   end

endmodule
